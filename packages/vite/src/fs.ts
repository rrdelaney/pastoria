import {createHash} from 'node:crypto';
import * as fs from 'node:fs/promises';
import * as path from 'node:path';

/**
 * Minimal filesystem used by the code generator to read templates and write
 * generated artifacts. Abstracted so tests can run against an in-memory FS.
 */
export interface GeneratorFileSystem {
  /** Returns the file's contents, or `undefined` if it does not exist. */
  readFile(filePath: string): Promise<string | undefined>;
  /** Writes a file, creating parent directories as needed. */
  writeFile(filePath: string, content: string): Promise<void>;
  /** Lists file names (not paths) directly inside `dirPath`. Empty if missing. */
  readDir(dirPath: string): Promise<string[]>;
  deleteFile(filePath: string): Promise<void>;
}

export const nodeFileSystem: GeneratorFileSystem = {
  async readFile(filePath) {
    try {
      return await fs.readFile(filePath, 'utf-8');
    } catch {
      return undefined;
    }
  },
  async writeFile(filePath, content) {
    await fs.mkdir(path.dirname(filePath), {recursive: true});
    await fs.writeFile(filePath, content, 'utf-8');
  },
  async readDir(dirPath) {
    try {
      const entries = await fs.readdir(dirPath, {withFileTypes: true});
      return entries.filter((e) => e.isFile()).map((e) => e.name);
    } catch {
      return [];
    }
  },
  async deleteFile(filePath) {
    await fs.rm(filePath, {force: true});
  },
};

/**
 * Regex to extract the checksum from a generated file's header comment.
 * Matches: @generated-checksum <hex-hash>
 */
const CHECKSUM_REGEX = /@generated-checksum ([a-f0-9]+)/;

function computeChecksum(content: string): string {
  return createHash('sha256').update(content).digest('hex');
}

function extractChecksum(content: string): string | null {
  const match = content.match(CHECKSUM_REGEX);
  return match?.[1] ?? null;
}

/**
 * Formats `content` with Prettier and writes it to `filePath` only if it
 * changed. A checksum of the unformatted content is stamped into the header
 * comment, so unchanged files are skipped without running Prettier.
 *
 * Returns true if the file was written, false if skipped as unchanged.
 */
export async function saveWithChecksum(
  fileSystem: GeneratorFileSystem,
  filePath: string,
  content: string,
): Promise<boolean> {
  const newChecksum = computeChecksum(content);
  const existingContent = await fileSystem.readFile(filePath);
  if (
    existingContent != null &&
    extractChecksum(existingContent) === newChecksum
  ) {
    return false;
  }

  // Loaded lazily: it's the slowest part of generation and often not needed.
  const prettier = await import('prettier');
  const formattedContent = await prettier.format(content, {
    parser: 'typescript',
    singleQuote: true,
  });

  // The header comment is the first thing in the file; insert the checksum on line 2.
  const contentWithChecksum = formattedContent.replace(
    '* This file was generated by `pastoria`.',
    `* This file was generated by \`pastoria\`.\n * @generated-checksum ${newChecksum}`,
  );

  await fileSystem.writeFile(filePath, contentWithChecksum);
  return true;
}
