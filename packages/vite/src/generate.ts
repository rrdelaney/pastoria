/**
 * @fileoverview Router Code Generator
 *
 * This script generates type-safe router configuration files by scanning TypeScript
 * source code in the project's `pastoria` directory.
 *
 * Usage:
 * - Add #pastoria/app.tsx to create a wrapper component for the app
 * - Add #pastoria/environment.ts to configure the application
 * - Add page.tsx files to #pastoria to create new routes
 *
 * The generator automatically creates Zod schemas for route parameters based on
 * TypeScript types, enabling runtime validation and type safety.
 *
 * All analysis is done by `PastoriaAnalyzer`; this file only builds source text.
 */

import * as path from 'node:path';
import pc from 'picocolors';
import {moduleSpecifier, type PastoriaAnalyzer} from './analyzer.js';
import {
  type GeneratorFileSystem,
  nodeFileSystem,
  saveWithChecksum,
} from './fs.js';
import {logInfo, logWarn} from './logger.js';
import {PastoriaMetadata} from './metadata.js';

const GENERATED_HEADER = `/*
 * This file was generated by \`pastoria\`.
 * Do not modify this file directly.
 */
`;

function escapeResourceName(routeName: string): string {
  return routeName
    .replace(/\[(\w+)\]/g, '$$$1')
    .replace(/\//g, '_')
    .replace(/^_/, '')
    .replace(/#/, '_')
    .replace(/_$/, '');
}

interface NamedImport {
  name: string;
  alias?: string;
}

interface ImportDeclaration {
  moduleSpecifier: string;
  namedImports?: (string | NamedImport)[];
  defaultImport?: string;
  isTypeOnly?: boolean;
}

function printImports(imports: ImportDeclaration[]): string {
  return imports
    .map((imp) => {
      const clauses: string[] = [];
      if (imp.defaultImport) clauses.push(imp.defaultImport);
      if (imp.namedImports) {
        const named = imp.namedImports.map((n) =>
          typeof n === 'string'
            ? n
            : n.alias
              ? `${n.name} as ${n.alias}`
              : n.name,
        );
        clauses.push(`{${named.join(', ')}}`);
      }

      const typeOnly = imp.isTypeOnly ? 'type ' : '';
      return `import ${typeOnly}${clauses.join(', ')} from '${imp.moduleSpecifier}';\n`;
    })
    .join('');
}

/** Inserts `text` after the last top-level import statement in `source`. */
function insertAfterImports(source: string, text: string): string {
  let insertAt = 0;
  for (const match of source.matchAll(/^import\b[^;]*;[^\n]*\n?/gm)) {
    insertAt = match.index + match[0].length;
  }

  return source.slice(0, insertAt) + text + source.slice(insertAt);
}

/**
 * Replaces the body of the object literal assigned to `const <name> = {...}`.
 * Templates include placeholder entries (e.g. `noop`) so they type-check on
 * their own; those are dropped.
 */
function replaceObjectLiteralBody(
  source: string,
  name: string,
  body: string,
): string {
  const declaration = `const ${name} = {`;
  const start = source.indexOf(declaration);
  if (start === -1) {
    throw new Error(`Template is missing \`${declaration}\``);
  }

  const bodyStart = start + declaration.length;
  let depth = 1;
  let i = bodyStart;
  for (; i < source.length && depth > 0; i++) {
    if (source[i] === '{') depth++;
    else if (source[i] === '}') depth--;
  }

  if (depth !== 0) {
    throw new Error(`Unbalanced braces in template object \`${name}\``);
  }

  return source.slice(0, bodyStart) + body + source.slice(i - 1);
}

export interface ExecutionContextOptions {
  fileSystem?: GeneratorFileSystem;
  templatesDir?: string;
}

export class PastoriaExecutionContext {
  static TEMPLATES_DIRECTORY = path.join(import.meta.dirname, '../templates');

  private readonly projectDir: string;
  private readonly fileSystem: GeneratorFileSystem;
  private readonly templatesDir: string;
  private metadata!: PastoriaMetadata;

  constructor(
    private readonly analyzer: PastoriaAnalyzer,
    options: ExecutionContextOptions = {},
  ) {
    this.projectDir = analyzer.projectDir;
    this.fileSystem = options.fileSystem ?? nodeFileSystem;
    this.templatesDir =
      options.templatesDir ?? PastoriaExecutionContext.TEMPLATES_DIRECTORY;
  }

  private outputPath(fileName: string) {
    return path.join(this.projectDir, '__generated__/router', fileName);
  }

  private async loadRouterTemplate(filename: string) {
    const templatePath = path.join(this.templatesDir, filename);
    const template = await this.fileSystem.readFile(templatePath);
    if (template == null) {
      throw new Error(`Could not read template ${templatePath}`);
    }

    const warningComment = `/*
 * This file was generated by \`pastoria\`.
 * Do not modify this file directly. Instead, edit the template at ${path.basename(templatePath)}.
 */

`;

    return warningComment + template;
  }

  /** Returns relative path of a file from the project root. This is typically one level above #pastoria. */
  private relativePathFromRoot(fileName: string) {
    return path.relative(this.projectDir, fileName).split(path.sep).join('/');
  }

  /** Returns relative path of a file from the #pastoria root. */
  private relativePathFromPastoria(fileName: string) {
    return path
      .relative(path.join(this.projectDir, 'pastoria'), fileName)
      .split(path.sep)
      .join('/');
  }

  /** Determines if a file generates a React route, e.g. is a page.tsx. */
  private isRoutablePageFile(fileName: string) {
    return path.basename(fileName) === 'page.tsx';
  }

  /** Returns a human-friendly generated abstract resource name for a source file under #pastoria. */
  private resourceNameForPastoriaSourceFile(fileName: string) {
    const pastoriaPath = this.relativePathFromPastoria(fileName);
    let routableName = '/' + path.posix.dirname(pastoriaPath);

    // Handle #pastoria/page.tsx as just /.
    if (routableName === '/.') routableName = '/';

    if (this.isRoutablePageFile(fileName)) {
      return routableName;
    } else {
      return `${routableName}#${path.posix.basename(pastoriaPath, '.tsx')}`;
    }
  }

  /**
   * Returns an absolute module specifier for a source file under #pastoria, e.g. #pastoria/route/[details]/page.
   */
  private moduleNameForPastoriaSourceFile(fileName: string) {
    const pastoriaPath = this.relativePathFromPastoria(fileName);
    return path.posix.join(
      '#pastoria',
      path.posix.dirname(pastoriaPath),
      path.posix.basename(pastoriaPath, path.posix.extname(pastoriaPath)),
    );
  }

  private entryPointFileNameForResource(fileName: string) {
    const resourceName = this.moduleNameForPastoriaSourceFile(fileName);
    const escapedName = escapeResourceName(
      resourceName.replace('#pastoria/', ''),
    );
    return escapedName + '.entrypoint.ts';
  }

  async generatePastoriaArtifacts() {
    // TODO: Add sanity checks that #pastoria/app.tsx and #pastoria/environment.ts exist.
    this.metadata = new PastoriaMetadata(this.analyzer, this.projectDir);

    await Promise.all([
      this.generateRouter(),
      this.generateJsResource(),
      this.generateServer(),
      this.generateEntryPointFiles(),
      this.generateHelperTypes(),
    ]);
  }

  private async generateRouter() {
    const {entryPointRoutes} = this.metadata;
    const outputPath = this.outputPath('router.tsx');
    let router = await this.loadRouterTemplate('router.tsx');

    const imports: ImportDeclaration[] = [];
    const routerConf: string[] = [];
    const routeMapping: string[] = [];

    for (const {routeName, routePath, fileName} of entryPointRoutes) {
      const escapedRouteName = escapeResourceName(routeName);
      imports.push({
        moduleSpecifier: moduleSpecifier(
          outputPath,
          this.outputPath(this.entryPointFileNameForResource(fileName)),
        ),
        namedImports: [
          {name: 'schema', alias: `${escapedRouteName}_EP_schema`},
          {name: 'entrypoint', alias: `${escapedRouteName}_EP_entrypoint`},
        ],
      });

      routerConf.push(`"${routeName}": {
  entrypoint: ${escapedRouteName}_EP_entrypoint,
  schema: ${escapedRouteName}_EP_schema,
} as const,`);

      routeMapping.push(`"${routePath}": ROUTER_CONF["${routeName}"],`);

      logInfo('Created route', pc.cyan(routeName));
    }

    router = insertAfterImports(router, printImports(imports));
    router = replaceObjectLiteralBody(
      router,
      'ROUTER_CONF',
      routerConf.join('\n'),
    );
    router = replaceObjectLiteralBody(
      router,
      'ROUTE_MAPPING',
      routeMapping.join('\n'),
    );

    await saveWithChecksum(this.fileSystem, outputPath, router);
  }

  private async generateJsResource() {
    const outputPath = this.outputPath('js_resource.ts');
    const template = await this.loadRouterTemplate('js_resource.ts');

    const resourceConf = this.metadata.resourceFiles.map(
      (fileName) => `"${this.resourceNameForPastoriaSourceFile(fileName)}": {
  src: "${this.relativePathFromRoot(fileName)}",
  loader: () => import("${this.moduleNameForPastoriaSourceFile(fileName)}").then(m => m.default),
},`,
    );

    await saveWithChecksum(
      this.fileSystem,
      outputPath,
      replaceObjectLiteralBody(
        template,
        'RESOURCE_CONF',
        resourceConf.join('\n'),
      ),
    );
  }

  private async generateServer() {
    const {serverRoutes} = this.metadata;
    const outputPath = this.outputPath('server.ts');
    const template = await this.loadRouterTemplate('server.ts');

    const imports: ImportDeclaration[] = [];
    const statements: string[] = [];

    let serverHandlerImportIndex = 0;
    for (const {fileName, routeName, routePath} of serverRoutes) {
      const importAlias = `e${serverHandlerImportIndex++}`;
      imports.push({
        moduleSpecifier: moduleSpecifier(outputPath, fileName),
        namedImports: [{name: 'default', alias: importAlias}],
      });

      statements.push(`router.use('${routePath}', ${importAlias});\n`);

      logInfo(
        'Created server route',
        pc.cyan(routeName),
        'for',
        pc.yellow(this.relativePathFromRoot(fileName)),
      );
    }

    await saveWithChecksum(
      this.fileSystem,
      outputPath,
      insertAfterImports(template, printImports(imports)).trimEnd() +
        '\n' +
        statements.join(''),
    );
  }

  private async generateHelperTypes() {
    const {resourceFiles} = this.metadata;
    if (resourceFiles.length === 0) {
      // TODO: delete the source file if we're not generating any helper types.
      return;
    }

    const imports: ImportDeclaration[] = [
      {
        moduleSpecifier: 'react-relay/hooks',
        namedImports: ['EntryPointProps', 'PreloadProps'],
        isTypeOnly: true,
      },
      {
        moduleSpecifier: 'zod/v4-mini',
        namedImports: ['z'],
        isTypeOnly: true,
      },
    ];

    const pageTypeHelpers: {
      routeName: string;
      escapedResourceName: string;
    }[] = [];

    for (const fileName of resourceFiles) {
      const entryPointFileName = path.basename(
        this.entryPointFileNameForResource(fileName),
        '.ts',
      );

      const escapedResourceName = path.basename(
        entryPointFileName,
        '.entrypoint',
      );

      imports.push({
        moduleSpecifier: `./${entryPointFileName}`,
        isTypeOnly: true,
        namedImports: [
          {name: 'Queries', alias: `${escapedResourceName}_EP_Queries`},
          {name: 'EntryPoints', alias: `${escapedResourceName}_EP_EntryPoints`},
          {
            name: 'RuntimeProps',
            alias: `${escapedResourceName}_EP_RuntimeProps`,
          },
          {name: 'ExtraProps', alias: `${escapedResourceName}_EP_ExtraProps`},
          {name: 'schema', alias: `${escapedResourceName}_EP_schema`},
          {
            name: 'PreloadPropsHelpers',
            alias: `${escapedResourceName}_EP_PreloadPropsHelpers`,
          },
        ],
      });

      pageTypeHelpers.push({
        routeName: this.resourceNameForPastoriaSourceFile(fileName),
        escapedResourceName,
      });
    }

    const content = `${GENERATED_HEADER}${printImports(imports)}
declare global {
  type PastoriaRouteName =
    ${pageTypeHelpers.map((r) => `| '${r.routeName}'`).join('    \n')};

  type PastoriaPageQueries = {
    ${pageTypeHelpers.map((r) => `['${r.routeName}']: ${r.escapedResourceName}_EP_Queries`).join(',')},
  };

  type PastoriaPageEntryPoints = {
    ${pageTypeHelpers.map((r) => `['${r.routeName}']: ${r.escapedResourceName}_EP_EntryPoints`).join(',')},
  };

  type PastoriaPageRuntimeProps = {
    ${pageTypeHelpers.map((r) => `['${r.routeName}']: ${r.escapedResourceName}_EP_RuntimeProps`).join(',')},
  };

  type PastoriaPageExtraProps = {
    ${pageTypeHelpers.map((r) => `['${r.routeName}']: ${r.escapedResourceName}_EP_ExtraProps`).join(',')},
  };

  type PastoriaPageProps<T extends PastoriaRouteName> = EntryPointProps<
    PastoriaPageQueries[T],
    PastoriaPageEntryPoints[T],
    PastoriaPageRuntimeProps[T],
    PastoriaPageExtraProps[T]
  >;

  type PastoriaPreloadPropsParams = {
    ${pageTypeHelpers.map((r) => `['${r.routeName}']: z.output<typeof ${r.escapedResourceName}_EP_schema>`).join(',')},
  };

  type PastoriaPreloadPropsHelpers = {
    ${pageTypeHelpers.map((r) => `['${r.routeName}']: ${r.escapedResourceName}_EP_PreloadPropsHelpers`).join(',')}
  };

  type GetPreloadProps<R extends PastoriaRouteName> = (params: PastoriaPreloadPropsHelpers[R]) =>
    PreloadProps<PastoriaPreloadPropsParams[R], PastoriaPageQueries[R], PastoriaPageEntryPoints[R], PastoriaPageExtraProps[R]>;

  type ModuleParams<T extends PastoriaRouteName> = PastoriaPreloadPropsParams[T]
}
`;

    await saveWithChecksum(
      this.fileSystem,
      this.outputPath('types.ts'),
      content,
    );
    logInfo('Created page helper types');
  }

  private async generateEntryPointFiles() {
    const expectedFiles = new Set(
      await Promise.all(
        this.metadata.resourceFiles.map((fileName) =>
          this.generateSingleEntryPointFile(fileName),
        ),
      ),
    );

    // Delete stale entrypoint files that no longer correspond to a resource.
    const generatedDir = path.join(this.projectDir, '__generated__/router');
    for (const entry of await this.fileSystem.readDir(generatedDir)) {
      if (entry.endsWith('.entrypoint.ts') && !expectedFiles.has(entry)) {
        await this.fileSystem.deleteFile(path.join(generatedDir, entry));
        logWarn('Removed stale entrypoint', pc.cyan(entry));
      }
    }
  }

  /** Builds the Zod schema for an entrypoint's URL params. */
  private getSchemaCode(
    moduleSchemaText: string | undefined,
    outputPath: string,
    queryVariables: Map<string, (targetFile: string) => string>,
  ): string {
    // Prefer copying the schema exported from the page.
    // TODO: Copy the original page file and remove everything but `schema` and the variables it uses.
    if (moduleSchemaText != null) {
      return moduleSchemaText;
    }

    // Fallback: generate from query variable types.
    if (queryVariables.size === 0) {
      return 'z.object({})';
    }

    const properties = Array.from(queryVariables)
      .map(([name, render]) => `${name}: ${render(outputPath)}`)
      .join(', ');

    return `z.object({${properties}})`;
  }

  /**
   * Collects all parameters used by `queries`.
   *
   * In the case of a conflict, later queries variables win.
   */
  private collectQueryParameters(
    fileName: string,
    queryNames: Iterable<string>,
  ) {
    const vars = new Map<string, (targetFile: string) => string>();
    for (const queryName of queryNames) {
      // TODO: Detect conflicting types among properties declared.
      for (const [name, render] of this.analyzer.getQueryVariables(
        fileName,
        queryName,
      )) {
        vars.set(name, render);
      }
    }

    return vars;
  }

  private async generateSingleEntryPointFile(fileName: string) {
    const resourceName = this.resourceNameForPastoriaSourceFile(fileName);
    const entryPointFileName = this.entryPointFileNameForResource(fileName);
    const outputPath = this.outputPath(entryPointFileName);
    const isRoutable = this.isRoutablePageFile(fileName);

    const moduleInfo = this.analyzer.getModuleInfo(fileName);
    const {queries, entryPoints: nestedEntryPoints, exports} = moduleInfo;
    const params = this.collectQueryParameters(fileName, queries.values());

    const hasQueriesExport = exports.has('Queries');
    const hasEntryPointsExport = exports.has('EntryPoints');
    const hasExtraPropsExport = exports.has('ExtraProps');
    const hasRuntimePropsExport = exports.has('RuntimeProps');

    if (hasRuntimePropsExport && isRoutable) {
      logWarn(
        `Route ${resourceName} has an exported RuntimeProps. Runtime props for routable resources are automatically generated and should not be overridden. This may cause type and runtime errors.`,
      );
    }

    // Import only the types that are actually exported from the module.
    const pageTypeImports: string[] = [];
    if (hasEntryPointsExport) pageTypeImports.push('EntryPoints');
    if (hasQueriesExport) pageTypeImports.push('Queries');
    if (hasExtraPropsExport) pageTypeImports.push('ExtraProps');
    if (hasRuntimePropsExport) pageTypeImports.push('RuntimeProps');

    const imports: ImportDeclaration[] = [];
    if (pageTypeImports.length > 0) {
      imports.push({
        moduleSpecifier: moduleSpecifier(outputPath, fileName),
        namedImports: pageTypeImports,
        isTypeOnly: true,
      });
    }

    // Required imports for scaffolding the file.
    imports.push(
      {
        moduleSpecifier: 'react-relay/hooks',
        namedImports: [
          'EntryPoint',
          'ThinNestedEntryPointParams',
          'ThinQueryParams',
        ],
        isTypeOnly: true,
      },
      {
        moduleSpecifier: 'zod/v4-mini',
        namedImports: ['z'],
      },
      {
        moduleSpecifier: './js_resource',
        namedImports: ['JSResource', 'ModuleType'],
      },
    );

    for (const queryName of queries.values()) {
      imports.push({
        moduleSpecifier: `#genfiles/queries/${queryName}$parameters`,
        defaultImport: `${queryName}Parameters`,
      });
    }

    for (const queryName of queries.values()) {
      imports.push({
        moduleSpecifier: `#genfiles/queries/${queryName}.graphql`,
        namedImports: [queryName, `${queryName}$variables`],
        isTypeOnly: true,
      });
    }

    for (const nestedResourceName of nestedEntryPoints.values()) {
      const escapedResourceName = escapeResourceName(nestedResourceName);
      imports.push({
        moduleSpecifier: `./${escapedResourceName}.entrypoint`,
        namedImports: [
          {name: 'entrypoint', alias: `${escapedResourceName}_entrypoint`},
          {name: 'schema', alias: `${escapedResourceName}_schema`},
        ],
      });
    }

    const schemaCode = this.getSchemaCode(
      moduleInfo.schemaText,
      outputPath,
      params,
    );

    const entryPointBody =
      moduleInfo.getPreloadPropsText != null
        ? this.printEntryPointWithPreloadProps(
            resourceName,
            moduleInfo.getPreloadPropsText,
            queries,
            nestedEntryPoints,
          )
        : this.printEntryPoint(fileName, resourceName, queries);

    const statements: string[] = [
      `const schema = ${schemaCode};`,
      `const entrypoint: EntryPoint<ModuleType<'${resourceName}'>, z.output<typeof schema>> = {
${entryPointBody}
};`,
    ];

    // Generate fallback types for any missing exports.
    if (!hasQueriesExport) {
      statements.push('type Queries = {};');
    }
    if (!hasEntryPointsExport) {
      statements.push('type EntryPoints = {};');
    }
    if (!hasRuntimePropsExport) {
      statements.push(
        isRoutable
          ? 'type RuntimeProps = { pathname: string, searchParams: URLSearchParams };'
          : 'type RuntimeProps = {};',
      );
    }
    if (!hasExtraPropsExport) {
      statements.push('type ExtraProps = {};');
    }

    // PreloadPropsHelpers is used by PastoriaPreloadPropsHelpers in types.ts as a helper
    // type for routes that override and export getPreloadProps.
    statements.push(`type PreloadPropsHelpers = {
  variables: z.output<typeof schema>;
  queries: {
    ${Array.from(queries)
      .map(
        ([queryAlias, queryName]) =>
          `${queryAlias}: (variables: ${queryName}$variables) => ThinQueryParams<${queryName}>`,
      )
      .join(',\n')}
  };
  entryPoints: {
    ${Array.from(nestedEntryPoints)
      .map(([entryPointAlias, nestedResourceName]) => {
        const escapedResourceName = escapeResourceName(nestedResourceName);
        return `${entryPointAlias}: (
          entryPointParams: z.output<typeof ${escapedResourceName}_schema>
        ) => ThinNestedEntryPointParams<
          EntryPoint<
            ModuleType<'${nestedResourceName}'>,
            ModuleParams<'${nestedResourceName}'>
          >
        >`;
      })
      .join(',\n')}
  }
};`);

    // Re-export the normalized types and schemas.
    statements.push(
      `export {entrypoint, schema, type EntryPoints, type Queries, type RuntimeProps, type ExtraProps, type PreloadPropsHelpers};`,
    );

    const content =
      GENERATED_HEADER +
      printImports(imports) +
      '\n' +
      statements.join('\n\n') +
      '\n';

    await saveWithChecksum(this.fileSystem, outputPath, content);
    logInfo('Created entrypoint for', pc.cyan(resourceName));

    return entryPointFileName;
  }

  /**
   * Creates the body of an EntryPoint object for a given #pastoria-based route file.
   *
   * @param fileName Path of the module under #pastoria.
   * @param resourceName Name of the JSResource of the root module.
   * @param queries Map of query reference name in the component to query name.
   */
  private printEntryPoint(
    fileName: string,
    resourceName: string,
    queries: Map<string, string>,
  ): string {
    const queryEntries = Array.from(queries).map(([queryRef, queryName]) => {
      // Each variable is written one-by-one to avoid spreading unused variables into any query.
      const varNames = Array.from(
        this.collectQueryParameters(fileName, [queryName]).keys(),
      );

      return `${queryRef}: {
  parameters: ${queryName}Parameters,
  variables: {${varNames.map((v) => `${v}: variables.${v}`).join(', ')}}
},`;
    });

    return `root: JSResource.fromModuleId('${resourceName}'),
getPreloadProps(variables) {
  return {
    queries: {
${queryEntries.join('\n')}
    },
    entryPoints: {},
  };
},`;
  }

  /**
   * Creates an entrypoint body for a route that has an exported getPreloadProps we should
   * use instead of the default generated one.
   */
  private printEntryPointWithPreloadProps(
    resourceName: string,
    getPreloadPropsText: string,
    queries: Map<string, string>,
    nestedEntryPoints: Map<string, string>,
  ): string {
    return `root: JSResource.fromModuleId('${resourceName}'),
getPreloadProps($variables) {
  return (${getPreloadPropsText})({
    variables: $variables,
    queries: {
      ${Array.from(queries)
        .map(
          ([queryAlias, queryName]) => `['${queryAlias}']: (variables) => ({
        parameters: ${queryName}Parameters,
        variables,
      })`,
        )
        .join(',\n')}
    },
    entryPoints: {
      ${Array.from(nestedEntryPoints)
        .map(
          ([
            entryPointAlias,
            nestedResourceName,
          ]) => `['${entryPointAlias}']: (entryPointParams) => ({
        entryPoint: ${escapeResourceName(nestedResourceName)}_entrypoint,
        entryPointParams,
      })`,
        )
        .join(',\n')}
    },
  } satisfies PreloadPropsHelpers);
},`;
  }
}
